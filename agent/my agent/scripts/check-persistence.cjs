/** 重启/重建验收：恢复服务端会话、文件、数据、对话和不可变结果，再登出重登校验。 */
const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');
const assert = require('node:assert/strict');
const { request } = createRequire(path.resolve(__dirname, '../frontend/package.json'))('playwright');
const root = path.resolve(__dirname, '..');
const expected = JSON.parse(fs.readFileSync(path.join(root, 'test-results/persistence.json'), 'utf8'));
const env = Object.fromEntries(fs.readFileSync(path.join(root, '.env.acceptance'), 'utf8').trim().split(/\r?\n/).map(line => {const i=line.indexOf('=');return [line.slice(0,i),line.slice(i+1)];}));
const baseURL = process.env.VIBE_URL || 'http://localhost:8080';
(async () => {
  const client = await request.newContext({ baseURL, storageState: path.join(root, '.env.acceptance-session.json') });
  const json = async endpoint => { const response=await client.get(endpoint); assert.equal(response.status(),200,endpoint);return response.json(); };
  const me = await json('/api/auth/me');
  assert.equal(me.username, expected.username);
  const table = await json(`/api/tables/${expected.table_id}`);
  assert.equal(table.total, expected.row_count);
  assert.deepEqual(table.fields.map(field=>field.name),['学号','班级','成绩']);
  assert.equal(table.rows.find(row=>row.values.c1==='001').values.c3,expected.updated_score);
  const result = await json(`/api/results/${expected.result_id}`);
  assert.deepEqual(result.rows.map(row=>row.c3),[90,80]);
  assert.equal(result.id,expected.result_id);
  const conversation = await json(`/api/conversations/${expected.conversation_id}`);
  assert.ok(conversation.messages.some(message=>message.result_id===expected.result_id));
  const file = await client.get(`/api/files/${expected.file_id}/download`);
  assert.equal(file.status(),200);
  assert.equal(require('node:crypto').createHash('sha256').update(await file.body()).digest('hex'),expected.file_sha256);
  const history = await json('/api/history');
  const mutation = history.operations.find(op=>op.action==='update'&&op.table_id===expected.table_id);
  assert.ok(mutation);
  const plan = await json(`/api/plans/${mutation.plan_id}`);
  assert.equal(plan.status,'executed');
  const catalogBeforeLogin = await json('/api/catalog');
  const parseTask = catalogBeforeLogin.tasks.find(task=>task.file_id===expected.file_id);
  assert.ok(parseTask);
  const task = await json(`/api/tasks/${parseTask.id}`);
  assert.equal(task.status,'completed');
  assert.ok(task.table_ids.includes(expected.table_id));
  assert.equal((await client.post('/api/auth/logout',{headers:{'X-CSRF-Token':me.csrf_token}})).status(),200);
  assert.equal((await client.get('/api/auth/me')).status(),401);
  assert.equal((await client.post('/api/auth/login',{data:{username:env.USERNAME,password:env.PASSWORD}})).status(),200);
  const catalog=await json('/api/catalog');
  assert.ok(catalog.tables.some(t=>t.id===expected.table_id));
  await client.storageState({path:path.join(root,'.env.acceptance-session.json')});
  const reportPath=path.join(root,'test-results/persistence-report.json');
  const reports=fs.existsSync(reportPath)?JSON.parse(fs.readFileSync(reportPath,'utf8')):[];
  reports.push({stage:process.env.VERIFICATION_STAGE||'restart',passed:['server session','saved rows and fields','immutable query snapshot','conversation','source file hash','audit','saved plan','completed parsing task','logout and relogin'],model_mode:catalog.model_mode});
  fs.writeFileSync(reportPath,JSON.stringify(reports,null,2));
  console.log(JSON.stringify(reports.at(-1)));
  await client.dispose();
})().catch(error=>{console.error(error.message);process.exitCode=1;});
